// Runs after `astro build`:
//  1. copies the PHP form handler (server/api) into dist/api
//  2. puts the gated whitepaper in dist/api/private (blocked from direct download)
//  3. writes dist/.htaccess: HTTPS + apex redirect, old WordPress URL redirects, caching, headers
import { cpSync, copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dist = join(root, "dist");
const products = JSON.parse(readFileSync(join(root, "src/data/products.json"), "utf8"));

// 1 + 2: server code and private files
cpSync(join(root, "server/api"), join(dist, "api"), {
  recursive: true,
  filter: (src) => !/config\.local\.php$|\/private\/data/.test(src),
});
const wp = join(root, "assets-src/private/Leadcrystal_TCO_White_Paper_v3.1_June2026.pdf");
if (existsSync(wp)) {
  mkdirSync(join(dist, "api/private"), { recursive: true });
  copyFileSync(wp, join(dist, "api/private/whitepaper.pdf"));
} else {
  console.log("postbuild: no local whitepaper PDF (expected on Hostinger); it is served from leadcrystal-private/");
}
rmSync(join(dist, "api/private/data"), { recursive: true, force: true });

// 3: redirects from the old WordPress site
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const pathOf = (url) => new URL(url).pathname;
const fileRedirects = [];
for (const p of products) {
  if (p.oldSpecSheet) fileRedirects.push([pathOf(p.oldSpecSheet), p.specSheet]);
  if (p.oldImage) fileRedirects.push([pathOf(p.oldImage), p.image]);
}
fileRedirects.push(
  ["/wp-content/uploads/2026/06/Leadcrystal-company-profile.pdf", "/downloads/Leadcrystal-company-profile.pdf"],
  ["/wp-content/uploads/2026/06/Leadcrystal_TCO_White_Paper_v3.1_June2026.pdf", "/lead-crystal-tco-whitepaper/"],
);

const htaccess = `# Generated by scripts/postbuild.mjs. Edit that file, not this one.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html
AddDefaultCharset utf-8

<IfModule mod_rewrite.c>
RewriteEngine On

# HTTPS and apex domain (works behind Cloudflare or another proxy too)
RewriteCond %{HTTPS} off
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteCond %{HTTP_HOST} ^(www\\.)?leadcrystal\\.co$ [NC]
RewriteRule ^ https://leadcrystal.co%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTP_HOST} ^www\\.leadcrystal\\.co$ [NC]
RewriteRule ^ https://leadcrystal.co%{REQUEST_URI} [R=301,L]

# Old WordPress endpoints: gone for good
RewriteRule ^(wp-admin|wp-login\\.php|xmlrpc\\.php|wp-json)(/.*)?$ - [G,L]

# Old WooCommerce and blog archive URLs
RewriteRule ^(shop|cart|checkout|my-account)(/.*)?$ /catalogue/ [R=301,L]
RewriteRule ^(product-tag|brand)/ /catalogue/ [R=301,L]
RewriteRule ^product-category/battery/?$ /catalogue/ [R=301,L]
RewriteRule ^products/?$ /catalogue/ [R=301,L]
RewriteRule ^(category|author|tag)/ /insights/ [R=301,L]
RewriteRule ^(feed|comments/feed)/?$ /insights/ [R=301,L]
RewriteCond %{QUERY_STRING} (^|&)(uicore-tb|p|page_id|post_type)= [NC]
RewriteRule ^$ /? [R=301,L]

# Old media library files (spec sheets, product photos, PDFs)
${fileRedirects.map(([from, to]) => `RewriteRule ^${esc(from.replace(/^\//, ""))}$ ${to} [R=301,L]`).join("\n")}
RewriteRule ^wp-content/ - [G,L]

# Directories without a trailing slash
RewriteCond %{REQUEST_FILENAME} -d
RewriteRule ^(.*[^/])$ /$1/ [R=301,L]
</IfModule>

<IfModule mod_headers.c>
  # Keep Hostinger's temporary domain (and any other non-production host) out of Google
  <If "%{HTTP_HOST} !~ /^(www\\.)?leadcrystal\\.co$/">
    Header always set X-Robots-Tag "noindex, nofollow"
  </If>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
  Header always set Strict-Transport-Security "max-age=31536000"
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
  <FilesMatch "\\.(webp|png|jpg|jpeg|svg|woff2|ico)$">
    Header set Cache-Control "public, max-age=2592000"
  </FilesMatch>
  <FilesMatch "\\.pdf$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
</IfModule>
<IfModule mod_headers.c>
  <If "%{REQUEST_URI} =~ m#^/_astro/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json application/xml image/svg+xml
</IfModule>
`;
writeFileSync(join(dist, ".htaccess"), htaccess);
// Which commit is live: https://<site>/version.txt
writeFileSync(join(dist, "version.txt"), `${process.env.GITHUB_SHA || "local"} ${new Date().toISOString()}\n`);
console.log(`postbuild: api copied, ${fileRedirects.length} file redirects, .htaccess written`);
